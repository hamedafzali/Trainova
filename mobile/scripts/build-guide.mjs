// Bundles the 3D movement guide (pixelwizards-gym-motion + three.js) into one
// self-contained HTML page for a WebView, so it works offline and needs no
// server. Output: src/guide/guideHtml.ts (generated, git-ignored).
// The package's body worker can't load from an inline page, so the body mesh
// builds on the page's own thread instead — the package falls back by itself.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = await build({
  entryPoints: [join(here, "../src/guide/entry.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
  logLevel: "warning",
  // `new URL("./body-worker.js", import.meta.url)` has no meaning in one inline file.
  define: { "import.meta.url": '"about:blank"' },
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><style>html,body,#stage{margin:0;height:100%;background:#141B25;overflow:hidden;touch-action:pan-y}</style></head><body><div id="stage"></div><script>${js}</script></body></html>`;
writeFileSync(
  join(here, "../src/guide/guideHtml.ts"),
  `// Generated by scripts/build-guide.mjs — do not edit.\nexport const GUIDE_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`guide: ${(html.length / 1024).toFixed(0)} KB`);
